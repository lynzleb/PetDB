#!/bin/zsh
# PetDB bootstrap — gets a fresh clone running end to end.
# Runs the non-secret setup steps in order and prints what to do next.
#
# Usage (from repo root):  zsh scripts/bootstrap.sh
#
# Prerequisites: Node 20+, Docker Desktop, npm.
# This does NOT set up the GitHub token (each user brings their own) —
# see scripts/env/README.md for that.

set -e

ROOT_DIR="${0:A:h:h}"
cd "$ROOT_DIR"

echo "==> PetDB bootstrap"
echo ""

# 1. Check prerequisites.
command -v node >/dev/null 2>&1 || { echo "ERROR: node not found. Install Node 20+."; exit 1; }
command -v docker >/dev/null 2>&1 || { echo "ERROR: docker not found. Install Docker Desktop."; exit 1; }

NODE_MAJOR=$(node -p "process.versions.node.split('.')[0]")
if [ "$NODE_MAJOR" -lt 20 ]; then
  echo "ERROR: Node 20+ required (found $(node --version))."
  exit 1
fi
echo "Node $(node --version), Docker present."

# 2. Ensure Docker daemon is running (start Docker Desktop on macOS if needed).
if ! docker info >/dev/null 2>&1; then
  echo "Docker daemon not running. Attempting to start Docker Desktop..."
  open -a Docker 2>/dev/null || true
  for i in $(seq 1 30); do
    docker info >/dev/null 2>&1 && break
    sleep 2
  done
  docker info >/dev/null 2>&1 || { echo "ERROR: Docker daemon still not running."; exit 1; }
fi
echo "Docker daemon is up."
echo ""

# 3. Install dependencies.
echo "==> Installing dependencies (npm workspaces)..."
npm install
echo ""

# 4. Start Postgres and wait for health.
echo "==> Starting Postgres..."
docker compose up -d
echo -n "Waiting for Postgres to be healthy"
for i in $(seq 1 30); do
  health=$(docker inspect --format '{{.State.Health.Status}}' petdb-postgres 2>/dev/null || echo "")
  [ "$health" = "healthy" ] && break
  echo -n "."
  sleep 2
done
echo ""
[ "$health" = "healthy" ] || { echo "ERROR: Postgres did not become healthy."; exit 1; }
echo "Postgres is healthy."
echo ""

# 5. Create backend/.env if missing.
if [ ! -f backend/.env ]; then
  cp backend/.env.example backend/.env
  echo "Created backend/.env from example."
else
  echo "backend/.env already exists — leaving it as is."
fi
echo ""

# 6. Migrate + seed. (Prisma client is generated by backend's postinstall.)
echo "==> Applying database migrations..."
npm run prisma:deploy --workspace backend
echo "==> Seeding sample data..."
npm run prisma:seed --workspace backend
echo ""

# 7. Optional: GitHub MCP token setup (macOS only, interactive).
#    Skipped when PETDB_SKIP_GITHUB=1 (e.g. when called from start.sh).
if [[ "$OSTYPE" == darwin* && "${PETDB_SKIP_GITHUB:-}" != "1" ]]; then
  echo "==> GitHub MCP token (optional)"
  echo "    Needed only if you'll commit / open PRs through the GitHub MCP server."
  printf "    Set up your GitHub token now? [y/N] "
  read -r ANSWER
  if [[ "$ANSWER" == [yY]* ]]; then
    zsh "$ROOT_DIR/scripts/env/install.sh" || echo "    (env install had an issue — see output above)"
    zsh "$ROOT_DIR/scripts/env/setup-github-pat.sh" || echo "    (token not set — run 'zsh scripts/env/setup-github-pat.sh' later)"
  else
    echo "    Skipped. Run 'zsh scripts/env/setup-github-pat.sh' anytime later."
  fi
  echo ""
fi

# Final banner (suppressed when PETDB_QUIET=1, e.g. called from start.sh).
if [[ "${PETDB_QUIET:-}" != "1" ]]; then
  echo "======================================================"
  echo " PetDB is ready."
  echo ""
  echo " Start the apps in two terminals:"
  echo "   npm run dev:backend    # API  -> http://localhost:3001"
  echo "   npm run dev:frontend   # app  -> http://localhost:5173"
  echo ""
  echo " ...or start both at once:  npm run dev"
  echo ""
  echo " Optional verification loop:"
  echo "   npm run install:browsers --workspace e2e   # one time"
  echo "   npm run verify"
  echo ""
  if [[ "$OSTYPE" == darwin* ]]; then
    echo " If you set up the GitHub token: fully quit Kiro (Cmd+Q) and reopen it,"
    echo " then approve GITHUB_PAT in Kiro's 'Mcp Approved Env Vars' prompt."
  fi
  echo "======================================================"
fi
